"""Generate the files that are derived from notebooks.toml.

- .github/workflows/build_all_images.yml: one job per node, wired by `needs`
- the image tree in README.md, between the tree markers

Pure: functions take text and return text. __main__ reads and writes the files.

The templates use `__NAME__` placeholders filled in with str.replace, not
f-strings: GitHub's `${{ }}` would otherwise need escaping as `${{{{ }}}}`.
"""

from manifest import Manifest, build_order

RESERVED_JOB_NAMES = {"plan", "tag"}  # jobs of the generated workflow itself
TREE_START = "<!-- tree:start"
TREE_END = "<!-- tree:end -->"

WORKFLOW_HEADER = """\
# GENERATED by `python scripts/image_builder generate` from notebooks.toml.
# DO NOT EDIT: change notebooks.toml or scripts/image_builder/generate.py instead.
#
# Builds the images selected by `image_builder plan`, one job per image, in
# tree order. When pushing, the final `tag` job gives the images that weren't
# rebuilt this run's tags. Called by docker_dev.yml, docker_main.yml and
# trigger_build_and_push.yml.
name: Build all images

on:
  workflow_call:
    inputs:
      tag_set:
        description: Tag set from notebooks.toml, e.g. dev or master
        type: string
        required: true
      since:
        description: Build what changed since this ref; empty builds everything
        type: string
        default: ""
      push:
        description: Push to every registry
        type: boolean
        default: false
    secrets:
      GH_TOKEN:
        required: true
      QUAY_USERNAME:
        required: true
      QUAY_SECRET:
        required: true

permissions:
  contents: read

jobs:
  plan:
    runs-on: ubuntu-26.04
    outputs:
      plan: ${{ steps.plan.outputs.plan }}
    steps:
      - name: Checkout (full history, needed for --since)
        uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
        with:
          fetch-depth: 0

      # A stale copy of this file would silently skip images that were added
      # to notebooks.toml (no job for them), so refuse to build at all.
      - name: Generated files up to date
        run: python3 scripts/image_builder generate --check

      - name: Plan
        id: plan
        env:
          TAG_SET: ${{ inputs.tag_set }}
          SINCE: ${{ inputs.since }}
        run: |
          if [ -n "$SINCE" ]; then scope=(--since "$SINCE"); else scope=(--all); fi
          plan=$(python3 scripts/image_builder plan \\
            --tag-set "$TAG_SET" "${scope[@]}" --compact)
          echo "$plan" | python3 -m json.tool
          echo "plan=$plan" >> "$GITHUB_OUTPUT"
"""

# A job runs when its image is in the plan and no job it needs has failed.
# `!cancelled() && !failure()` replaces the default `success()`, which would
# also skip the job when its parent was skipped (not in the plan).
JOB_CONDITION = (
    "!cancelled() && !failure() && "
    "contains(fromJSON(needs.plan.outputs.plan).images, '__IMAGE__')"
)

# `plan` must be in `needs` of every job: a job can only read the outputs of
# jobs it depends on directly.
JOB_TEMPLATE = """
  __IMAGE__:
    needs: [__NEEDS__]
    if: ${{ __CONDITION__ }}
    uses: ./.github/workflows/_build_image.yml
    with:
      image: __IMAGE__
      plan: ${{ needs.plan.outputs.plan }}
      push: ${{ inputs.push }}
    secrets: inherit
"""


# Runs after every image job: gives the images this run didn't rebuild the
# run's tags, so per-day and per-commit tags cover the whole image set.
# `!failure()`: if any build failed, no half-built set is labelled as complete.
TAG_JOB_TEMPLATE = """
  tag:
    needs:
__NEEDS__
    if: ${{ !cancelled() && !failure() && inputs.push }}
    runs-on: ubuntu-26.04
    steps:
      - name: Checkout
        uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1

      - name: Login to ghcr.io
        uses: docker/login-action@81c6f93d4bc991e510b342a00b419b3bb4efc5c6 # v4.7.0
        with:
          registry: ghcr.io
          username: ${{ github.repository_owner }}
          password: ${{ secrets.GH_TOKEN }}

      - name: Login to quay.io
        uses: docker/login-action@81c6f93d4bc991e510b342a00b419b3bb4efc5c6 # v4.7.0
        with:
          registry: quay.io
          username: ${{ secrets.QUAY_USERNAME }}
          password: ${{ secrets.QUAY_SECRET }}

      - name: Complete tag sets
        env:
          PLAN: ${{ needs.plan.outputs.plan }}
        run: python3 scripts/image_builder complete-tags --plan "$PLAN"
"""


class GenerateError(Exception):
    """Raised when a file can't be generated, e.g. missing README markers."""


def workflow(manifest: Manifest) -> str:
    reserved = sorted(RESERVED_JOB_NAMES & manifest.nodes.keys())
    if reserved:
        raise GenerateError(f"image name(s) reserved for workflow jobs: {reserved}")

    order = build_order(manifest.nodes)
    jobs = []
    for name in order:
        parent = manifest.nodes[name].parent
        needs = "plan" if parent is None else f"plan, {parent}"
        jobs.append(
            JOB_TEMPLATE.replace("__CONDITION__", JOB_CONDITION)
            .replace("__NEEDS__", needs)
            .replace("__IMAGE__", name)
        )
    tag_needs = "\n".join(f"      - {name}" for name in ["plan", *order])
    jobs.append(TAG_JOB_TEMPLATE.replace("__NEEDS__", tag_needs))
    return WORKFLOW_HEADER + "".join(jobs)


def readme_with_tree(readme: str, tree: str) -> str:
    """Replace everything between the tree markers with `tree` in a code block."""
    start = readme.find(TREE_START)
    end = readme.find(TREE_END)
    if start == -1 or end == -1 or end < start:
        raise GenerateError(
            f"README.md needs the markers '{TREE_START} ... -->' and '{TREE_END}'"
        )
    after_start_line = readme.index("\n", start) + 1
    return readme[:after_start_line] + f"```\n{tree}\n```\n" + readme[end:]


if __name__ == "__main__":
    raise SystemExit("not a script: run `python scripts/image_builder -h` instead")
