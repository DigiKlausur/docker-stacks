import pytest
from generate import GenerateError, readme_with_tree, workflow
from helpers import make_data
from manifest import parse


@pytest.fixture
def generated():
    return workflow(parse(make_data()))  # base-nb (e2x) ── child-nb


def job(text: str, name: str) -> str:
    """The lines of one job in the generated workflow."""
    start = text.index(f"\n  {name}:\n")
    end = text.find("\n\n", start + 1)
    return text[start : end if end != -1 else None]


def test_header_marks_the_file_as_generated(generated):
    assert generated.startswith("# GENERATED by `python scripts/image_builder generate`")


def test_plan_job_refuses_to_build_with_stale_generated_files(generated):
    assert "run: python3 scripts/image_builder generate --check" in generated


def test_root_job_only_needs_the_plan(generated):
    assert "needs: [plan]" in job(generated, "base-nb")


def test_child_job_needs_the_plan_and_its_parent(generated):
    child = job(generated, "child-nb")
    assert "needs: [plan, base-nb]" in child
    assert "contains(fromJSON(needs.plan.outputs.plan).images, 'child-nb')" in child
    assert "image: child-nb" in child


def test_e2x_variants_get_their_own_job(generated):
    assert "needs: [plan, base-nb]" in job(generated, "base-nb-exam")


def test_reserved_job_names_are_rejected():
    images = {"plan": {"base": "x:1"}}
    with pytest.raises(GenerateError, match="reserved"):
        workflow(parse(make_data(images)))


README = """\
# Title

<!-- tree:start (generated) -->
```
old tree
```
<!-- tree:end -->

## Next
"""


def test_readme_tree_is_replaced():
    assert readme_with_tree(README, "new tree") == README.replace("old tree", "new tree")


def test_readme_update_is_idempotent():
    once = readme_with_tree(README, "new tree")
    assert readme_with_tree(once, "new tree") == once


def test_readme_without_markers_fails():
    with pytest.raises(GenerateError, match="markers"):
        readme_with_tree("# Title\n", "tree")
